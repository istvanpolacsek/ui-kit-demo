  HTMLButtonElement,
  PrimaryButtonDestructiveProps
>(function PrimaryButtonDestructive(
  { state = "Default", size = "Large", mode = "Light", ...rest },
  ref,
) {
  return (
    <StyledRoot
      aria-label="Delete button"
      {...rest}
      ref={ref}
      $state={state}
      $size={size}
      $mode={mode}
    >
      {["Default", "Hover", "Disabled"].includes(state) && (
        <StyledDeleteButton $state={state} $mode={mode}>
          {"Delete button"}
        </StyledDeleteButton>
      )}
      {state === "Loading" && <IndicatorLoading type={"Dark"} />}
    </StyledRoot>
  );
});
